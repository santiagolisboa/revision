#include <unistd.h>

void	ft_sub(int *a, int b)
{
	*a = *a - b;
}

#include <stdio.h>
int	main(void)
{
	int	x;

	x = 10;
	ft_sub(&x, 2);
	printf("%d\n", x);
	return (0);
}
